// Shared by every page: stylesheet, the display name (names.json), header/footer and small helpers.
import './style.css';
import names from '../../names.json';

export { names };
export const S = names.short;
export const BLOG = 'https://ben3d.ca/blog/houston-stratified-noise';
export const PR = 'https://github.com/mrdoob/three.js/pull/35429';
export const REPO = 'https://github.com/bhouston/houston-stratified-noise';

// Figures are imported from the committed results directory, so they are fingerprinted and follow the base path.
const figures = import.meta.glob( '../../results/**/*.webp', { eager: true, query: '?url', import: 'default' } );
export const figureUrl = ( path ) => figures[ `../../results/${path}` ];

export const el = ( html ) => { const t = document.createElement( 'template' ); t.innerHTML = html.trim(); return t.content.firstElementChild; };

// **bold** and `code` in the reading texts
export const md = ( text ) => text.replace( /&/g, '&amp;' ).replace( /</g, '&lt;' ).replace( /\*\*(.+?)\*\*/g, '<strong>$1</strong>' ).replace( /`(.+?)`/g, '<code>$1</code>' );

// reading texts carry {S} where the short name of the noise goes
export const r = ( text ) => md( text.replaceAll( '{S}', S ) );
export const list = ( items, tag = 'ul' ) => `<${tag}>${items.map( ( i ) => `<li>${r( i )}</li>` ).join( '' )}</${tag}>`;

// A table as the Python analyses emit it: { title, head, rows }, first column = row label. `cols` keeps a subset of columns.
export function dataTable( t, { cols, caption = true } = {} ) {

	const keep = ( row ) => cols ? [ row[ 0 ], ...cols.map( ( c ) => row[ c ] ) ] : row;
	const rows = t.rows.map( ( row ) => `<tr${row[ 0 ] === S || row[ 0 ].startsWith( S + ' (' ) ? ' class="self"' : ''}>${keep( row ).map( ( c ) => `<td>${c}</td>` ).join( '' )}</tr>` );
	return `${caption && t.title ? `<p class="caption">${md( t.title )}</p>` : ''}<div class="table"><table><thead><tr>${keep( t.head ).map( ( h ) => `<th>${h}</th>` ).join( '' )}</tr></thead><tbody>${rows.join( '' )}</tbody></table></div>`;

}

export const command = ( cmd ) => `<p class="cmd">Regenerate: <code>${cmd}</code></p>`;

export function figure( path, alt, caption = '' ) {

	return `<figure><a href="${figureUrl( path )}"><img src="${figureUrl( path )}" alt="${alt}" loading="lazy"></a>${caption && `<figcaption>${md( caption )}</figcaption>`}</figure>`;

}

// table: { head, rows: [ [ label, ...cells ] ], keys }; `limit` keeps the first rows only.
export function table( t, limit = Infinity ) {

	const rows = t.rows.slice( 0, limit ).map( ( r, i ) => `<tr${t.keys?.[ i ] === 'hsn' ? ' class="self"' : ''}>${r.map( ( c ) => `<td>${c}</td>` ).join( '' )}</tr>` );
	return `<div class="table"><table><thead><tr><th>Method</th>${t.head.map( ( h ) => `<th>${h}</th>` ).join( '' )}</tr></thead><tbody>${rows.join( '' )}</tbody></table></div>`;

}

const pages = [ [ './', 'Overview' ], [ 'results.html', 'Results' ], [ 'explorer.html', 'Explorer' ] ];
const here = location.pathname.split( '/' ).pop() || './';

document.body.prepend( el( `<header>
	<a class="title" href="./">${names.name}</a>
	<nav>${pages.map( ( [ href, label ] ) => `<a href="${href}"${href === here || ( href === './' && here === 'index.html' ) ? ' aria-current="page"' : ''}>${label}</a>` ).join( '' )}
	<a href="${BLOG}">Blog post</a><a href="${PR}">Three.js PR</a><a href="${REPO}">GitHub</a></nav>
</header>` ) );

document.body.append( el( `<footer>${names.name} (${S}). Code MIT, by Ben Houston. Every number and figure on this site is generated by the scripts in <a href="${REPO}">the repository</a>.</footer>` ) );
